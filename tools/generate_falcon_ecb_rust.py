def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--coverage-json", type=Path, default=DEFAULT_COVERAGE_JSON)
    args = parser.parse_args()

    samples = json.loads(args.input.read_text(encoding="utf-8"))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_generated_rust(samples), encoding="utf-8")
    subprocess.run(["rustfmt", str(args.output)], check=True)
    print(args.output)
    if args.coverage_json is not None:
        args.coverage_json.parent.mkdir(parents=True, exist_ok=True)
        args.coverage_json.write_text(
            json.dumps(build_coverage_payload(samples), indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        print(args.coverage_json)
    return 0


