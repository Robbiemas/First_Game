        "        rotation,",
        "        rotation_quat,",
        "        use_quaternion,",
        "        scale: SourceVec3Gen {",
        "            x: anim.scale.x * blend + live.scale.x * inv_blend,",
        "            y: anim.scale.y * blend + live.scale.y * inv_blend,",
        "            z: anim.scale.z * blend + live.scale.z * inv_blend,",
        "        },",
