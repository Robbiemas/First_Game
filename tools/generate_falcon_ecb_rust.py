        "    let len = falcon_quat_len_sq(q).sqrt();",
        "    if len <= f32::EPSILON {",
        "        return SourceQuatGen { x: 0.0, y: 0.0, z: 0.0, w: 1.0 };",
        "    }",
        "    SourceQuatGen { x: q.x / len, y: q.y / len, z: q.z / len, w: q.w / len }",
        "}",
        "",
        "fn falcon_eval_source_ecb_from_srts(",
        "    srts: &[SourceSrt; FALCON_SOURCE_COSTUME_JOINTS[0].len()],",
        "    flags: u32,",
