        "            x: anim.translation.x * blend + live.translation.x * inv_blend,",
        "            y: anim.translation.y * blend + live.translation.y * inv_blend,",
        "            z: anim.translation.z * blend + live.translation.z * inv_blend,",
        "        },",
        "    }",
        "}",
        "",
        "fn falcon_quat_from_euler(rotation: SourceVec3Gen) -> SourceQuatGen {",
        "    let matrix = SourceMatrix::from_euler_rotation(rotation, SourceVec3Gen { x: 1.0, y: 1.0, z: 1.0 }, SourceVec3Gen::default(), None);",
        "    falcon_quat_from_rotation_matrix(matrix)",
        "}",
        "",
        "fn falcon_quat_from_rotation_matrix(matrix: SourceMatrix) -> SourceQuatGen {",
        "    let m = matrix.m;",
        "    let trace = m[0][0] + m[1][1] + m[2][2];",
        "    if trace > 0.0 {",
        "        let s = (trace + 1.0).sqrt() * 2.0;",
        "        return falcon_quat_normalize(SourceQuatGen {",
        "            w: 0.25 * s,",
        "            x: (m[2][1] - m[1][2]) / s,",
        "            y: (m[0][2] - m[2][0]) / s,",
        "            z: (m[1][0] - m[0][1]) / s,",
        "        });",
        "    }",
        "    if m[0][0] > m[1][1] && m[0][0] > m[2][2] {",
        "        let s = (1.0 + m[0][0] - m[1][1] - m[2][2]).sqrt() * 2.0;",
        "        return falcon_quat_normalize(SourceQuatGen {",
        "            w: (m[2][1] - m[1][2]) / s,",
        "            x: 0.25 * s,",
        "            y: (m[0][1] + m[1][0]) / s,",
        "            z: (m[0][2] + m[2][0]) / s,",
        "        });",
        "    }",
        "    if m[1][1] > m[2][2] {",
        "        let s = (1.0 + m[1][1] - m[0][0] - m[2][2]).sqrt() * 2.0;",
        "        return falcon_quat_normalize(SourceQuatGen {",
        "            w: (m[0][2] - m[2][0]) / s,",
        "            x: (m[0][1] + m[1][0]) / s,",
        "            y: 0.25 * s,",
        "            z: (m[1][2] + m[2][1]) / s,",
        "        });",
        "    }",
        "    let s = (1.0 + m[2][2] - m[0][0] - m[1][1]).sqrt() * 2.0;",
        "    falcon_quat_normalize(SourceQuatGen {",
        "        w: (m[1][0] - m[0][1]) / s,",
        "        x: (m[0][2] + m[2][0]) / s,",
        "        y: (m[1][2] + m[2][1]) / s,",
        "        z: 0.25 * s,",
        "    })",
        "}",
        "",
        "fn falcon_quat_slerp(a: SourceQuatGen, b: SourceQuatGen, t: f32) -> SourceQuatGen {",
        "    let dot = (a.x * b.x + a.y * b.y + a.z * b.z + a.w * b.w).clamp(-1.0, 1.0);",
        "    if dot > 0.9995 {",
        "        return falcon_quat_normalize(SourceQuatGen {",
        "            x: a.x + t * (b.x - a.x),",
        "            y: a.y + t * (b.y - a.y),",
        "            z: a.z + t * (b.z - a.z),",
        "            w: a.w + t * (b.w - a.w),",
        "        });",
        "    }",
        "    let theta_0 = dot.acos();",
        "    let theta = theta_0 * t;",
        "    let sin_theta = theta.sin();",
        "    let sin_theta_0 = theta_0.sin();",
        "    let s0 = theta.cos() - dot * sin_theta / sin_theta_0;",
        "    let s1 = sin_theta / sin_theta_0;",
        "    falcon_quat_normalize(SourceQuatGen {",
        "        x: s0 * a.x + s1 * b.x,",
        "        y: s0 * a.y + s1 * b.y,",
        "        z: s0 * a.z + s1 * b.z,",
        "        w: s0 * a.w + s1 * b.w,",
        "    })",
        "}",
        "",
        "fn falcon_quat_len_sq(q: SourceQuatGen) -> f32 {",
        "    q.x * q.x + q.y * q.y + q.z * q.z + q.w * q.w",
        "}",
        "",
