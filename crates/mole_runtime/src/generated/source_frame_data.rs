pub(crate) fn source_figatree_chunks() -> &'static [RuntimeFigatreeChunk<'static>] {
    SOURCE_FIGATREE_CHUNKS
        .get_or_init(|| {
            SOURCE_FIGATREE_BUNDLE_INDEX
                .iter()
                .map(|entry| {
                    let end = entry.start + entry.len;
                    RuntimeFigatreeChunk {
                        source_action_key: entry.source_action_key,
                        bytes: &SOURCE_FIGATREE_BUNDLE_BYTES[entry.start..end],
                    }
                })
                .collect()
        })
        .as_slice()
}

